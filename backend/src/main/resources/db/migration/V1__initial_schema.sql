-- Fresh-install schema matching the inspected UPIQ 2.0 PostgreSQL schema before amount conversion.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(255),
    email varchar(255) NOT NULL,
    google_subject varchar(255),
    password varchar(255) NOT NULL,
    full_name varchar(255),
    role varchar(255),
    created_at timestamp(6) without time zone NOT NULL,
    active boolean NOT NULL,
    last_login_ip varchar(255),
    last_login_at timestamp(6) without time zone,
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_google_subject_key UNIQUE (google_subject),
    CONSTRAINT users_role_check CHECK (role IS NULL OR role IN ('USER', 'ADMIN'))
);

CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    type varchar(255) NOT NULL,
    description varchar(255),
    color varchar(255),
    icon varchar(255),
    user_id bigint NOT NULL
);

CREATE TABLE transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    amount double precision NOT NULL,
    type varchar(255) NOT NULL,
    category varchar(255) NOT NULL,
    description varchar(255),
    date timestamp(6) without time zone NOT NULL,
    payment_method varchar(255),
    import_identity varchar(100),
    CONSTRAINT uk_transactions_user_import_identity UNIQUE (user_id, import_identity)
);

CREATE INDEX idx_tx_user_cat_date ON transactions (user_id, category, date);
CREATE INDEX idx_tx_user_date ON transactions (user_id, date);
CREATE INDEX idx_tx_user_type_date ON transactions (user_id, type, date);
