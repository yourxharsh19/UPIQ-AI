CREATE TABLE budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category varchar(255),
    period_start date NOT NULL,
    amount numeric(19,2) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_budgets_positive_amount CHECK (amount > 0),
    CONSTRAINT ck_budgets_period_month_start CHECK (EXTRACT(DAY FROM period_start) = 1),
    CONSTRAINT ck_budgets_category_nonblank CHECK (category IS NULL OR length(btrim(category)) > 0)
);

CREATE UNIQUE INDEX uk_budgets_user_total_month
    ON budgets (user_id, period_start)
    WHERE category IS NULL;

CREATE UNIQUE INDEX uk_budgets_user_category_month
    ON budgets (user_id, period_start, lower(btrim(category)))
    WHERE category IS NOT NULL;

CREATE INDEX idx_budgets_user_period ON budgets (user_id, period_start);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event_key varchar(255) NOT NULL,
    type varchar(50) NOT NULL,
    title varchar(200) NOT NULL,
    message varchar(1000) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at timestamp(6) without time zone,
    dismissed_at timestamp(6) without time zone,
    CONSTRAINT uk_notifications_user_event UNIQUE (user_id, event_key)
);

CREATE INDEX idx_notifications_user_inbox
    ON notifications (user_id, dismissed_at, created_at DESC);

CREATE INDEX idx_notifications_user_unread
    ON notifications (user_id, read_at)
    WHERE dismissed_at IS NULL;
